/**
 * Орнаментальная линия — фирменный элемент.
 *
 * Қошқар мүйіз («бараний рог») — повторяющийся геометрический модуль.
 * Берём его НЕ как текстуру и не как иллюстрацию, а как одну непрерывную
 * линию: так национальное входит геометрией, а не фольклором. Это же
 * решает главную проблему демонстрации — линия не требует ни одной
 * фотографии, поэтому страница выглядит законченной на заглушках.
 *
 * Путь строится единым штрихом (без разрывов «M»), иначе DrawSVG будет
 * перепрыгивать пером и рисунок развалится.
 */

export const UNIT_HEIGHT = 200;
export const RAIL_WIDTH = 64;

export function ornamentPath(units: number): string {
  const cx = RAIL_WIDTH / 2;
  let d = `M ${cx} 0`;

  for (let i = 0; i < units; i++) {
    const y = i * UNIT_HEIGHT;

    // стойка
    d += ` L ${cx} ${y + 40}`;
    // правый рог: быстро наружу, медленно завиваясь обратно
    d += ` C ${cx} ${y + 58}, 62 ${y + 56}, 59 ${y + 80}`;
    d += ` C ${57} ${y + 100}, 34 ${y + 97}, ${cx} ${y + 84}`;
    // стойка
    d += ` L ${cx} ${y + 120}`;
    // левый рог, зеркально
    d += ` C ${cx} ${y + 138}, 2 ${y + 136}, 5 ${y + 160}`;
    d += ` C ${7} ${y + 180}, 30 ${y + 177}, ${cx} ${y + 164}`;
    // стойка до следующего модуля
    d += ` L ${cx} ${y + UNIT_HEIGHT}`;
  }

  return d;
}

/** Компактная версия знака — для углов заглушек и маркеров. */
export const ORNAMENT_MARK_PATH =
  "M12 2 C12 8, 20 7, 19 12 C18 16, 13 15.2, 13 11 M12 22 C12 16, 4 17, 5 12 C6 8, 11 8.8, 11 13";
