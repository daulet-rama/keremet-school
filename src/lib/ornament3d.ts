/**
 * Тот же қошқар мүйіз, но в трёх измерениях.
 *
 * Плоский путь из ornament.ts развёрнут в пространственную кривую: каждый
 * рог уходит не только вбок, но и по оси Z, поэтому завиток становится
 * настоящей спиралью и не пересекает сам себя. Именно это отличает
 * структурный 3D-объект от декоративной кляксы — форма остаётся
 * фирменным знаком, читается как орнамент с любого ракурса и не является
 * произвольной геометрией, поставленной ради эффекта.
 *
 * Координаты в тех же условных единицах, что и SVG (модуль высотой 200),
 * центрированные по X. Y направлен вниз — знак меняется при построении.
 */

/** Один модуль: стойка, правый рог со спиралью, стойка, левый рог зеркально. */
const UNIT: [number, number, number][] = [
  [0, 0, 0],
  [0, -38, 0],
  [16, -52, 5],
  [26, -72, 11],
  [22, -88, 14],
  [8, -92, 10],
  [2, -82, 4],
  [0, -118, 0],
  [-16, -132, -5],
  [-26, -152, -11],
  [-22, -168, -14],
  [-8, -172, -10],
  [-2, -162, -4],
  [0, -200, 0],
];

const UNIT_HEIGHT = 200;

/** Масштаб: приводим условные единицы SVG к мировым единицам сцены. */
const SCALE = 1 / 26;

/**
 * Точки кривой для указанного числа модулей, отцентрованные по вертикали,
 * чтобы объект вращался вокруг собственной середины, а не уезжал из кадра.
 */
export function ornamentCurvePoints(units: number): [number, number, number][] {
  const pts: [number, number, number][] = [];

  for (let u = 0; u < units; u++) {
    const offset = u * UNIT_HEIGHT;
    // Последняя точка модуля совпадает с первой точкой следующего —
    // пропускаем её, иначе CatmullRom получит дубль и даст излом.
    const stop = u === units - 1 ? UNIT.length : UNIT.length - 1;
    for (let i = 0; i < stop; i++) {
      const [x, y, z] = UNIT[i];
      pts.push([x, y - offset, z]);
    }
  }

  const total = UNIT_HEIGHT * units;
  return pts.map(([x, y, z]) => [
    x * SCALE,
    (y + total / 2) * SCALE,
    z * SCALE,
  ]);
}
